import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("20-condition programme responds to case selection and audited what-if changes", async ({ page }) => {
  const errors: string[] = []; page.on("pageerror", (e) => errors.push(e.message));
  await page.goto("/");
  await page.getByRole("link", { name: /Open research workbench/ }).first().click();
  await expect(page).toHaveURL(/\/research(?:\?[^#]*)?#synthetic-programme$/);
  const programme = page.getByTestId("synthetic-programme");
  await expect(programme).toHaveAttribute("aria-busy", "false", { timeout: 30_000 });
  await programme.getByRole("navigation", { name: "Investigation steps" }).getByRole("link", { name: "1 · Context", exact: true }).click();
  await expect(page).toHaveURL(/#programme-context$/);
  await expect(programme.getByRole("button", { name: "Type 1 diabetes", exact: true })).toBeVisible();
  await programme.getByRole("button", { name: "Type 1 diabetes", exact: true }).click();
  await programme.getByRole("combobox", { name: "Synthetic case", exact: true }).selectOption("SYN-P-T1D-002");
  await expect(programme.getByRole("region", { name: "Synthetic laboratory timeline" })).toContainText("HbA1c");
  await programme.getByRole("button", { name: "Run discovery planning demo", exact: true }).click();
  await expect(programme.getByRole("article", { name: "Synthetic discovery plan" })).toContainText("Unusable lab records: 3");
  await programme.getByRole("button", { name: "Screen fictional trial criteria", exact: true }).click();
  const criterion = programme.getByRole("region", { name: "SYN-TRIAL-T1D-A criteria", exact: true }).getByRole("row").filter({ hasText: "nonnegative marker" });
  await expect(criterion).toContainText("unknown");
  await programme.getByText("Interactive what-if editor · synthetic records only", { exact: true }).click();
  await programme.getByRole("spinbutton", { name: "What-if marker value", exact: true }).fill("15");
  await programme.getByRole("combobox", { name: "What-if marker quality", exact: true }).selectOption("valid");
  await programme.getByRole("spinbutton", { name: "What-if sleep hours", exact: true }).fill("8");
  await programme.getByRole("button", { name: "Apply synthetic what-if", exact: true }).click();
  await expect(programme.getByRole("article", { name: "Synthetic discovery plan" })).toHaveCount(0);
  await programme.getByRole("button", { name: "Run discovery planning demo", exact: true }).click();
  await expect(programme.getByRole("article", { name: "Synthetic discovery plan" })).toContainText("Unusable lab records: 2");
  await programme.getByRole("button", { name: "Screen fictional trial criteria", exact: true }).click();
  await expect(criterion).toContainText("satisfied");
  await programme.getByRole("textbox", { name: "Synthetic programme analyst note", exact: true }).fill("Synthetic what-if inspected in browser test.");
  const [download] = await Promise.all([page.waitForEvent("download"), programme.getByRole("button", { name: "Export synthetic case dossier", exact: true }).click()]);
  const dossier = JSON.parse(await readFile((await download.path())!, "utf8"));
  expect(dossier.patient.id).toBe("SYN-P-T1D-002");
  expect(dossier.scenarioEdits).toHaveLength(1);
  expect(dossier.discovery.audit.aiInferencePerformed).toBe(false);
  expect(dossier.confirmedEligible).toBe(false);
  expect(dossier.analystNote).toContain("Synthetic what-if");
  await programme.getByRole("combobox", { name: "Programme domain", exact: true }).selectOption("Gut");
  await expect(programme.getByRole("button", { name: "Crohn’s disease", exact: true })).toBeVisible();
  await expect(programme.getByRole("button", { name: "Type 1 diabetes", exact: true })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
